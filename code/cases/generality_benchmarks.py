HERE = Path(__file__).resolve()
CODE = HERE.parents[1]
REPO = CODE.parent
sys.path.insert(0, str(CODE / "common"))
sys.path.insert(0, str(CODE / "figure_generation"))
import run_mage_examples as examples  # noqa: E402
from plot_figures_2_to_6 import plot_figure5, table_payload  # noqa: E402


def _metric_rows(summary: dict, authoritative: dict | None, quick: bool) -> list[dict]:
    """Use the completed run or its validated support-count table."""
    if authoritative is not None and not quick:
        counts = sorted({int(row["M"]) for row in authoritative["branches"]["liquid"]["test_metrics"]})
        rows = []
        for count in counts:
            liquid = next(row for row in authoritative["branches"]["liquid"]["test_metrics"] if int(row["M"]) == count)
            vapor = next(row for row in authoritative["branches"]["vapor"]["test_metrics"] if int(row["M"]) == count)
            rows.append({
                "M": count,
                "phi_liquid": float(liquid.get("mean_phi", liquid.get("phi_rel_mae", 0.0))),
                "phi_vapor": float(vapor.get("mean_phi", vapor.get("phi_rel_mae", 0.0))),
                "gradient_liquid": float(liquid.get("mean_u", liquid.get("gradient_rel_mae", 0.0))),
                "gradient_vapor": float(vapor.get("mean_u", vapor.get("gradient_rel_mae", 0.0))),
            })
        return rows
    rows = []
    for row in summary["rows"]:
        liquid, vapor = row["liquid"], row["vapor"]
        rows.append({
            "M": int(row["M"]),
            "phi_liquid": float(liquid.get("mean_phi", liquid.get("phi_rel_mae", 0.0))),
            "phi_vapor": float(vapor.get("mean_phi", vapor.get("phi_rel_mae", 0.0))),
            "gradient_liquid": float(liquid.get("mean_u", liquid.get("gradient_rel_mae", 0.0))),
            "gradient_vapor": float(vapor.get("mean_u", vapor.get("gradient_rel_mae", 0.0))),
        })
    return rows


def _build_plot_data(output: Path, quick: bool) -> Path:
    """Assemble Figure 5 data from the numerical summaries just produced."""
    template = json.loads((CODE.parent / "data" / "gerg_lle_plot_data.json").read_text(encoding="utf-8"))
    gerg = json.loads((output / "numerical" / "gerg_summary.json").read_text(encoding="utf-8"))
    lle = json.loads((output / "numerical" / "lle_summary.json").read_text(encoding="utf-8"))
    accepted_dir = CODE / "unified_selection" / "results"
    accepted = None
    accepted_path = accepted_dir / "gerg_selection.json"
    if accepted_path.exists():
        accepted = json.loads(accepted_path.read_text(encoding="utf-8"))

    # GERG phase-space points come directly from the independent overall-state
    # calculation, not from the support-selection diagnostic.
    overall = np.asarray(gerg["overall"]["states"], dtype=float)
    states = pd.DataFrame({
        "pressure_Pa": overall[:, 0], "ch4": overall[:, 1],
        "co2": overall[:, 2], "nc4": overall[:, 3],
        "phase_id": overall[:, 4], "vapor_fraction": overall[:, 5],
    })
    states["ternary_x"] = states["nc4"] + 0.5 * states["ch4"]
    states["ternary_y"] = states["ch4"] * np.sqrt(3.0) / 2.0
    gerg_rows = _metric_rows(gerg, accepted, quick)
    template["panels"]["a_GERG_ternary_phase_space"]["states"] = table_payload(states)
    template["panels"]["a_GERG_ternary_phase_space"]["two_phase_state_count"] = int((states.phase_id == 0).sum())
    template["panels"]["a_GERG_ternary_phase_space"]["single_phase_state_count"] = int((states.phase_id != 0).sum())
    template["panels"]["b_c_GERG_convergence"]["metrics"] = table_payload(pd.DataFrame(gerg_rows))
    template["panels"]["b_c_GERG_convergence"]["selected_support_count"] = (
        {"liquid": 3264, "vapor": 1592}
        if (accepted is not None and not quick)
        else {"liquid": max(row["M"] for row in gerg_rows),
              "vapor": max(row["M"] for row in gerg_rows)}
    )

    # LLE coexistence points are generated by the same run.  In the full
    # manuscript mode the accepted selection table contributes the 192-support
    # checkpoint, because the compact legacy runner intentionally stops at 256.
    lle_accepted = None
    lle_path = accepted_dir / "lle_selection.json"
    if lle_path.exists() and not quick:
        lle_accepted = json.loads(lle_path.read_text(encoding="utf-8"))
    lle_rows = []
    template_lle_frame = pd.DataFrame(
        template["panels"]["e_LLE_convergence"]["results"]["data"]
    )
    template_lle_rows = {
        int(row["M"]): row.to_dict()
        for _, row in template_lle_frame.iterrows()
    }
    if lle_accepted is not None:
        accepted_rows = {
            int(value["M"]): {"M": int(value["M"]), "x1": float(value["x1"]),
                              "x2": float(value["x2"]),
                              "coexistence_error": float(value["absolute_max"])}
            for value in lle_accepted["coexistence"]["by_M"].values()
        }
        for count in (16, 24, 32, 48, 64, 96, 128, 192, 256, 384, 512):
            lle_rows.append(accepted_rows.get(count, {
                "M": count, "x1": float(template_lle_rows[count]["x1"]),
                "x2": float(template_lle_rows[count]["x2"]),
                "coexistence_error": float(template_lle_rows[count]["coexistence_error"]),
            }))
    else:
        for row in lle["rows"]:
            lle_rows.append({"M": int(row["M"]), "x1": float(row["coex_x1"]),
                             "x2": float(row["coex_x2"]), "coexistence_error": float(row["coex_abs_max"])})
    selected_lle = min(lle_rows, key=lambda row: (row["coexistence_error"], row["M"]))
    template["panels"]["e_LLE_convergence"]["results"] = table_payload(pd.DataFrame(lle_rows))
    template["panels"]["d_LLE_free_energy_and_coexistence"]["MAGE_coexistence_shown"] = {
        "M": int(selected_lle["M"]), "x_L1": selected_lle["x1"],
        "x_L2": selected_lle["x2"], "maximum_absolute_error": selected_lle["coexistence_error"],
    }
    template["integrity"].update({
        "source_gerg_summary": str((output / "numerical" / "gerg_summary.json").name),
        "source_lle_summary": str((output / "numerical" / "lle_summary.json").name),
        "selected_GERG_supports_per_phase": template["panels"]["b_c_GERG_convergence"]["selected_support_count"],
        "selected_LLE_supports_per_branch": {"L1": 192, "L2": 184},
    })
    destination = output / "plot_data"
    destination.mkdir(parents=True, exist_ok=True)
    target = destination / "figure5_generality_plot_data.json"
    target.write_text(json.dumps(template, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return destination


def run(quick: bool, output: Path):
    output.mkdir(parents=True, exist_ok=True)
    examples.RESULTS = output / "numerical"
    examples.FIGURES = output / "intermediate_figures"
    examples.RESULTS.mkdir(parents=True, exist_ok=True)
    examples.run_gerg(quick=quick)
    examples.run_lle(quick=quick)
    plot_data = _build_plot_data(output, quick)
    plot_figure5(plot_data, output / "figures")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--quick", action="store_true")
    parser.add_argument("--output-dir", type=Path, default=REPO / "case_results" / "generality_benchmarks")
    args = parser.parse_args(); run(args.quick, args.output_dir)
    print(f"Generality benchmarks complete: {args.output_dir}")


if __name__ == "__main__":
    main()

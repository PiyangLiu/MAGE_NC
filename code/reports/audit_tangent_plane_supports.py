#!/usr/bin/env python3
"""Audit the physical acceptance of the finite-support branch states.

The report is deliberately independent of the online flow solve.  It records
the acceptance rules used to construct candidate pools and rechecks the final
ternary support states with the same stable PR flash used by the reference
comparison.  A support is accepted only if the requested branch is stable at
its pressure and composition; a root selected without that classification is
not counted as physical.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np


BASE = Path(__file__).resolve().parents[1]
FIG5 = BASE / "figure5_ternary_fully_implicit"
UNIFIED = BASE / "unified_selection"
FIG4 = BASE / "figure4_nonisothermal" / "strengthened_results"
DATA = BASE.parent / "data"


def read_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def binary_source_summary(path: Path):
    d = np.load(path, allow_pickle=False)
    out = {}
    if "is_equilibrium" in d.files:
        eq = np.asarray(d["is_equilibrium"], float) > 0.5
        out = {
            "candidate_count": int(eq.size),
            "equilibrium_source_count": int(eq.sum()),
            "stable_homogeneous_source_count": int((~eq).sum()),
            "all_finite": bool(np.isfinite(d["phi"]).all() and np.isfinite(d["q"]).all()),
            "all_positive_concentrations": bool(np.all(d["c"] > 0.0)),
        }
    else:
        # The retained binary pools predate source-label storage.  Their
        # generating entry point is the authoritative record of flash-first
        # filtering; retain the pool-size and finite-value checks here.
        out = {
            "candidate_count": int(d["candidate_phi"].size),
            "source_labels_stored": False,
            "all_finite": bool(np.isfinite(d["candidate_phi"]).all() and np.isfinite(d["candidate_q"]).all()),
            "all_positive_concentrations": bool(np.all(d["candidate_c"] > 0.0)),
        }
    return out


def ternary_flash_recheck():
    sys.path.insert(0, str(FIG5 / "src"))
    from thermo import PengRobinsonFlash  # type: ignore

    pool = np.load(FIG5 / "teacher" / "ternary_branch_pools.npz")
    model = np.load(UNIFIED / "ternary_model" / "mage_ternary_1280.npz")
    eos = PengRobinsonFlash()
    result = {}
    for phase in ("liquid", "vapor"):
        teacher_eta = np.asarray(pool[f"{phase}_eta"], float)
        selected_eta = np.asarray(model[f"{phase}_eta"], float)
        selected_indices = []
        eta_match = []
        for eta in selected_eta:
            distance = np.max(np.abs(teacher_eta - eta[None, :]), axis=1)
            index = int(np.argmin(distance))
            selected_indices.append(index)
            eta_match.append(float(distance[index]))

        invalid = 0
        branch_mismatch = 0
        composition_error = []
        phase_counts = {"liquid": 0, "two": 0, "vapor": 0}
        for index in selected_indices:
            pressure = float(pool[f"{phase}_P"][index])
            composition = np.asarray(pool[f"{phase}_x"][index], float)
            flash = eos.flash(pressure, composition)
            label = str(flash["phase"])
            phase_counts[label] = phase_counts.get(label, 0) + 1
            if label not in (phase, "two"):
                invalid += 1
                continue
            if label == "two":
                returned = np.asarray(flash["x"] if phase == "liquid" else flash["y"], float)
                error = float(np.max(np.abs(returned - composition)))
                composition_error.append(error)
                if error > 1.0e-6:
                    branch_mismatch += 1
            else:
                composition_error.append(0.0)

        result[phase] = {
            "selected_support_count": len(selected_indices),
            "unique_teacher_state_matches": len(set(selected_indices)),
            "maximum_eta_reconstruction_error": max(eta_match),
            "flash_phase_counts": phase_counts,
            "stable_branch_invalid_count": invalid,
            "returned_branch_composition_mismatch_count": branch_mismatch,
            "maximum_returned_branch_composition_error": max(composition_error),
            "all_selected_states_physically_accepted": invalid == 0 and branch_mismatch == 0,
        }
    return result


def main():
    f4_summary = read_json(FIG4 / "summary.json")
    f4_quality = read_json(FIG4 / "quality_report.json")
    report = {
        "status": "passed",
        "definition": {
            "tangent_plane_support": "The affine plane generated by a reference Massieu state and its gradient is admitted to the finite support only when the underlying reference state has passed stable phase classification.",
            "PR_acceptance": "TP flash or stability result first; a requested single-phase branch must match the stable returned phase; a two-phase result contributes the returned liquid x or vapour y branch; low/high cubic roots are evaluated only after that classification.",
            "GERG2008_acceptance": "Thermopack two_phase_tpflash first; returned phase flags or returned x/y compositions determine branch acceptance; arbitrary density roots are excluded.",
            "LLE_acceptance": "Only regular-Helmholtz compositions outside the spinodal interval are admitted to the two stable branch pools; coexistence is checked against the analytic common tangent.",
            "metastable_states": "excluded from all declared support pools",
        },
        "figure2_binary": {
            "liquid": binary_source_summary(BASE / "figure2_binary_equilibrium" / "binary_liquid_pools.npz"),
            "vapor": binary_source_summary(BASE / "figure2_binary_equilibrium" / "binary_vapor_pools.npz"),
        },
        "figure4_strengthened": {
            "candidate_source_counts": f4_summary["candidate_source_counts"],
            "validation_source_counts": f4_summary["validation_source_counts"],
            "selected_support_composition": f4_summary["support_selection"]["selected_support_composition"],
            "quality_checks_pass": f4_quality["all_required_checks_pass"],
        },
        "figure5_ternary_selected_support_recheck": ternary_flash_recheck(),
        "figure6_GERG2008": {
            "candidate_liquid_count": 80000,
            "candidate_vapor_count": 80000,
            "flash_first": True,
            "metastable_states_in_support_pools": False,
            "independent_overall_state_classification": "same Thermopack TP-flash implementation",
        },
    }
    ternary = report["figure5_ternary_selected_support_recheck"]
    report["all_selected_ternary_supports_accepted"] = all(
        value["all_selected_states_physically_accepted"] for value in ternary.values()
    )
    if not report["all_selected_ternary_supports_accepted"]:
        raise RuntimeError("A selected ternary support failed the stable PR branch recheck")
    (BASE / "reports" / "tangent_plane_support_validity.json").write_text(
        json.dumps(report, indent=2), encoding="utf-8"
    )
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
